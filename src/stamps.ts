// as outras setas são a seta para cima girada
const rot = (rows: string[], turns: number): string[] => {
  let r = rows;
  for (let t = 0; t < turns; t++) {
    const n = r.length;
    r = r.map((_, y) => Array.from({ length: n }, (_, x) => r[n - 1 - x][y]).join(""));
  }
  return r;
};
ART.right = { label: "➡️", rows: rot(ART.up.rows, 1) };
ART.down = { label: "⬇️", rows: rot(ART.up.rows, 2) };
ART.left = { label: "⬅️", rows: rot(ART.up.rows, 3) };

/** Ordem em que aparecem na malha de emojis (5 por linha). */
const ORDER = [
  "smile", "sad", "heart", "star", "sun",
  "check", "x", "thumbs", "bolt", "music",
  "up", "down", "left", "right", "wifi",
  "moon", "cloud", "rain", "flower", "house",
  "bell", "lock", "bulb", "battery", "skull",
];

export interface Stamp {
  id: string;
  label: string;
  size: number;
  /** pixels[y * size + x] = 1 quando aceso */
  pixels: Uint8Array;
}

export const STAMPS: Stamp[] = ORDER.map((id) => {
  const { label, rows } = ART[id];
  const size = rows.length;
  if (rows.some((row) => row.length !== size)) throw new Error(`emoji ${id}: linhas com tamanho errado`);
  const pixels = new Uint8Array(size * size);
  rows.forEach((row, y) => {
    for (let x = 0; x < size; x++) if (row[x] === "#") pixels[y * size + x] = 1;
  });
  return { id, label, size, pixels };
});
